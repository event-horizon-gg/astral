// Keep GPUI's control icons identical to the Electron UI's Lucide icons.
// Run from the repository root with: node scripts/sync-native-icons.cjs
const fs = require('node:fs');
const path = require('node:path');
const React = require('react');
const { renderToStaticMarkup } = require('react-dom/server');
const lucide = require('lucide-react');
const root = path.resolve(__dirname, '..');
const icons = {
  search: 'Search', loader: 'LoaderCircle', user: 'User', chevron: 'ChevronDown', command: 'Command',
  layers: 'Layers', 'chevron-right': 'ChevronRight', cloud: 'Cloud', monitor: 'Monitor',
  logout: 'LogOut', more: 'MoreHorizontal', history: 'History', refresh: 'RefreshCw',
  folder: 'FolderOpen', globe: 'Globe', drive: 'HardDrive', external: 'ExternalLink',
  'arrow-up-right': 'ArrowUpRight', 'arrow-right': 'ArrowRight', download: 'ArrowDownToLine',
  alert: 'AlertCircle', plus: 'Plus', package: 'Package', settings: 'SlidersHorizontal',
  trash: 'Trash2', gear: 'Settings', close: 'X', 'check-circle': 'CheckCircle2', check: 'Check', 'shield-check': 'ShieldCheck', sun: 'Sun', moon: 'Moon',
};
const directory = path.join(root, 'native/assets/icons');
fs.mkdirSync(directory, { recursive: true });
for (const [name, component] of Object.entries(icons)) {
  const svg = renderToStaticMarkup(React.createElement(lucide[component], { color: 'white' }));
  fs.writeFileSync(path.join(directory, name + '.svg'), svg + '\n');
}
fs.copyFileSync(path.join(path.dirname(require.resolve('lucide-react/package.json')), 'LICENSE'), path.join(directory, 'LICENSE'));
fs.writeFileSync(path.join(root, 'native/src/ui_icons.rs'),
  '// Generated by scripts/sync-native-icons.cjs from lucide-react (ISC).\n' +
  'pub fn load(path: &str) -> Option<&\'static [u8]> {\n    Some(match path {\n' +
  Object.keys(icons).map(name => `        "${name}" => include_bytes!("../assets/icons/${name}.svg"),`).join('\n') +
  '\n        _ => return None,\n    })\n}\n');
